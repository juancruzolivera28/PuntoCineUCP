CREATE DATABASE IF NOT EXISTS puntocine
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE puntocine;

DROP TABLE IF EXISTS compra_butacas;
DROP TABLE IF EXISTS compras;
DROP TABLE IF EXISTS medios_pago;
DROP TABLE IF EXISTS butacas;
DROP TABLE IF EXISTS funciones;
DROP TABLE IF EXISTS peliculas;
DROP TABLE IF EXISTS salas;
DROP TABLE IF EXISTS cines;
DROP TABLE IF EXISTS usuarios;

CREATE TABLE usuarios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  rol VARCHAR(20) NOT NULL DEFAULT 'cliente',
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE cines (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(50) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  zona VARCHAR(100) NOT NULL,
  direccion VARCHAR(255) NOT NULL,
  horario_boleteria VARCHAR(100) NOT NULL,
  mapa_query VARCHAR(255) NOT NULL
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE salas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  cine_id INT NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  filas INT NOT NULL DEFAULT 6,
  columnas INT NOT NULL DEFAULT 8,
  FOREIGN KEY (cine_id) REFERENCES cines(id)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE peliculas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(150) NOT NULL UNIQUE,
  titulo VARCHAR(150) NOT NULL,
  genero VARCHAR(50) NOT NULL,
  duracion_min INT NOT NULL,
  clasificacion VARCHAR(10) NOT NULL,
  sinopsis TEXT NOT NULL,
  director VARCHAR(150) NOT NULL,
  elenco VARCHAR(255) NOT NULL,
  idioma VARCHAR(100) NOT NULL,
  poster_url VARCHAR(255) NOT NULL
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE funciones (
  id INT AUTO_INCREMENT PRIMARY KEY,
  pelicula_id INT NOT NULL,
  sala_id INT NOT NULL,
  horario TIME NOT NULL,
  precio DECIMAL(10,2) NOT NULL,
  FOREIGN KEY (pelicula_id) REFERENCES peliculas(id),
  FOREIGN KEY (sala_id) REFERENCES salas(id)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE butacas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  sala_id INT NOT NULL,
  fila CHAR(1) NOT NULL,
  numero INT NOT NULL,
  codigo VARCHAR(5) NOT NULL,
  FOREIGN KEY (sala_id) REFERENCES salas(id),
  UNIQUE KEY sala_codigo (sala_id, codigo)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE medios_pago (
  id INT AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(50) NOT NULL
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE compras (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  direccion VARCHAR(255) NOT NULL,
  telefono VARCHAR(30) NOT NULL,
  email VARCHAR(150) NOT NULL,
  medio_pago_id INT NOT NULL,
  usuario_id INT NULL,
  total DECIMAL(10,2) NOT NULL,
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (medio_pago_id) REFERENCES medios_pago(id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE compra_butacas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  compra_id INT NOT NULL,
  funcion_id INT NOT NULL,
  butaca_id INT NOT NULL,
  precio DECIMAL(10,2) NOT NULL,
  FOREIGN KEY (compra_id) REFERENCES compras(id),
  FOREIGN KEY (funcion_id) REFERENCES funciones(id),
  FOREIGN KEY (butaca_id) REFERENCES butacas(id),
  UNIQUE KEY funcion_butaca (funcion_id, butaca_id)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

